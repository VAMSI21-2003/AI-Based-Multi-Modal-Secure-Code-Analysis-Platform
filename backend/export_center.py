_DOCX_ACCENT = RGBColor(0x2A, 0x78, 0xD6)
_DOCX_MUTED = RGBColor(0x52, 0x51, 0x4E)
_DOCX_CRITICAL = RGBColor(0xD0, 0x3B, 0x3B)


def _docx_heading(doc, text, level=1, color=_DOCX_ACCENT):
    h = doc.add_heading(text, level=level)
    for run in h.runs:
        run.font.color.rgb = color
    return h


def _docx_table(doc, headers, rows):
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = "Light Grid Accent 1"
    hdr_cells = table.rows[0].cells
    for i, h in enumerate(headers):
        hdr_cells[i].text = str(h)
        for p in hdr_cells[i].paragraphs:
            for run in p.runs:
                run.font.bold = True
    for row in rows:
        cells = table.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = str(val)
    return table


def build_word_report(scan: dict, line_risks: list, recs: list, intel: dict) -> bytes:
    """Full technical report as a .docx -- same coverage as the developer PDF."""
    doc = docx.Document()

    title = doc.add_heading("Developer Security Report", level=0)
    for run in title.runs:
        run.font.color.rgb = RGBColor(0x0B, 0x0B, 0x0B)

    meta = doc.add_paragraph()
    meta.add_run(f"{scan.get('filename', '-')} — {scan.get('project_name', '')}").bold = True
    ts = doc.add_paragraph(f"Generated {dt.datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')}")
    ts.runs[0].font.color.rgb = _DOCX_MUTED

    _docx_heading(doc, "Verdict & Scores", level=1)
    scores = intel.get("scores", {}) if intel.get("available") else {}
    _docx_table(doc, ["Field", "Value"], [
        ["Verdict", scan["verdict"]],
        ["Risk Level", scan["risk_level"]],
        ["Vulnerability Probability", f"{scan['vuln_probability']:.2f}%"],
        ["Confidence", f"{scan['confidence']:.2f}%"],
        ["Model Used", scan["model_used"]],
        ["Quality Score", str(scores.get("quality", "-"))],
        ["Maintainability Index", str(scores.get("maintainability_index", "-"))],
        ["Security Score", str(scores.get("security_score", "-"))],
        ["Performance Score", str(scores.get("performance_score", "-"))],
    ])

    if intel.get("available") and intel.get("functions"):
        _docx_heading(doc, "Function Statistics", level=1)
        _docx_table(
            doc,
            ["Function", "LOC", "CC", "Nesting", "Calls", "MI"],
            [[f["name"], f["loc"], f["cyclomatic_complexity"], f["max_nesting"], f["call_count"], f["maintainability_index"]] for f in intel["functions"][:25]],
        )

    if line_risks:
        _docx_heading(doc, "Line-Level Findings", level=1)
        _docx_table(
            doc,
            ["Line", "Severity", "CWE", "Reason"],
            [[lr["line"], lr["severity"], ", ".join(lr.get("cwe", [])) or "-", "; ".join(lr["reasons"])[:120]] for lr in line_risks[:40]],
        )

    if recs:
        _docx_heading(doc, "Recommendations", level=1)
        for panel in recs:
            doc.add_heading(panel["title"], level=2)
            for tip in panel.get("tips", []):
                doc.add_paragraph(tip, style="List Bullet")

    footer = doc.add_paragraph()
    footer.add_run(
        "Generated by an automated multi-modal AI classifier (CodeBERT + AST + software metrics, XGBoost). "
        "Informs, does not replace, a human security review."
    ).font.color.rgb = _DOCX_MUTED

    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


