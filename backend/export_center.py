def _ent_score_chart(scores: dict) -> Drawing:
    """A real embedded bar chart (Phase 5, priority #8) -- not just tables --
    visualizing the same 4 composite scores as the kv table above it."""
    labels = ["Security", "Quality", "Maintainability", "Performance"]
    mi = scores.get("maintainability_index", 0) or 0
    values = [
        scores.get("security_score", 0) or 0,
        scores.get("quality", 0) or 0,
        min(100, mi),  # MI is conventionally 0-100 already, clamp defensively
        scores.get("performance_score", 0) or 0,
    ]
    colors_list = [colors.HexColor("#0ca30c"), colors.HexColor("#2a5fd6"), colors.HexColor("#9085e9"), colors.HexColor("#c98500")]

    d = Drawing(460, 130)
    chart = HorizontalBarChart()
    chart.x = 90
    chart.y = 10
    chart.width = 340
    chart.height = 105
    chart.data = [values]
    chart.categoryAxis.categoryNames = labels
    chart.categoryAxis.labels.fontSize = 8
    chart.categoryAxis.labels.fillColor = _ENT_INK
    chart.valueAxis.valueMin = 0
    chart.valueAxis.valueMax = 100
    chart.valueAxis.labels.fontSize = 7
    chart.bars.strokeWidth = 0
    chart.barWidth = 12
    for i, c in enumerate(colors_list):
        chart.bars[(0, i)].fillColor = c
    d.add(chart)
    return d


def _ent_kv_table(rows, col_widths=(190, 290)):
    tbl = Table(rows, colWidths=list(col_widths))
    tbl.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.4, _ENT_HAIRLINE),
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#f1f1ee")),
        ("TOPPADDING", (0, 0), (-1, -1), 5), ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
    ]))
    return tbl


def build_enterprise_pdf(scan: dict, line_risks: list, recs: list, intel: dict, architecture: dict, eval_curves: dict) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, topMargin=20 * mm, bottomMargin=20 * mm, leftMargin=20 * mm, rightMargin=20 * mm)
    ss = _enterprise_styles()
    el = []

    # ── Cover page ──────────────────────────────────────────────────────────
    risk_color = RISK_COLOR_MAP.get(scan["risk_level"], _ENT_ACCENT)
    el.append(Spacer(1, 50))
    el.append(Table([[""]], colWidths=[170 * mm], rowHeights=[3], style=TableStyle([("BACKGROUND", (0, 0), (-1, -1), risk_color)])))
    el.append(Spacer(1, 26))
    el.append(Paragraph("SecureCode AI", ss["EntCoverSub"]))
    el.append(Paragraph("Enterprise Security Report", ss["EntCoverTitle"]))
    el.append(Spacer(1, 8))
    el.append(Paragraph(f"{scan.get('project_name', 'Untitled Project')} &middot; {scan.get('filename', '-')}", ss["EntCoverSub"]))
    el.append(Paragraph(f"Generated {dt.datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')}", ss["EntMuted"]))
    el.append(Spacer(1, 40))

    safety_score = round(max(0.0, 100.0 - scan["vuln_probability"]), 1)
    grade = _grade(safety_score)
    cover_rows = [
        ["Verdict", scan["verdict"]],
        ["Risk Level", scan["risk_level"]],
        ["Safety Score", f"{safety_score:.0f} / 100  (Grade {grade})"],
        ["Confidence", f"{scan['confidence']:.1f}%"],
        ["Detection Model", scan["model_used"]],
        ["Lines of Code", str(scan.get("loc", "-"))],
    ]
    el.append(_ent_kv_table(cover_rows))
    el.append(Spacer(1, 60))
    el.append(HRFlowable(width="100%", color=_ENT_HAIRLINE, thickness=0.6))
    el.append(Spacer(1, 8))
    el.append(Paragraph(
        "Automated analysis generated by a multi-modal AI classifier (CodeBERT semantic embeddings + AST structural "
        "features + software metrics, fused and classified by a trained XGBoost model). This report is intended to "
        "inform a human security review, not replace one. Confidential -- for internal distribution.",
        ss["EntMuted"],
    ))
    el.append(PageBreak())

    # ── Executive summary ───────────────────────────────────────────────────
    el.append(Paragraph("Executive Summary", ss["EntSectionTitle"]))
    verdict_word = "requires attention before deployment" if scan["verdict"] == "VULNERABLE" else "shows no significant automated findings"
    el.append(Paragraph(
        f"This file <b>{verdict_word}</b>. The automated analysis assigns a safety score of <b>{safety_score:.0f}/100</b> "
        f"(grade <b>{grade}</b>), with the model reporting <b>{scan['confidence']:.1f}%</b> confidence in its verdict.",
        ss["EntBody"],
    ))
    el.append(Spacer(1, 10))
    scores = intel.get("scores", {}) if intel.get("available") else {}
    el.append(_ent_kv_table([
        ["Security Score", f"{scores.get('security_score', '-')}/100"],
        ["Quality Score", f"{scores.get('quality', '-')}/100"],
        ["Maintainability Index", str(scores.get("maintainability_index", "-"))],
        ["Performance Score", f"{scores.get('performance_score', '-')}/100"],
        ["Functions Analyzed", str(intel.get("function_count", "-"))],
        ["Dangerous APIs Found", str(len(intel.get("dangerous_apis", [])))],
    ]))
    if scores:
        el.append(Spacer(1, 12))
        el.append(_ent_score_chart(scores))

    # ── Architecture overview ───────────────────────────────────────────────
    el.append(Paragraph("Architecture Overview", ss["EntSubTitle"]))
    fp = architecture.get("feature_pipeline", {}) if architecture else {}
    el.append(Paragraph(
        f"Every file is analyzed through three independent branches -- {fp.get('ast_dimensions', 11)} AST structural "
        f"features, {fp.get('metrics_dimensions', 13)} software-quality metrics, and a {fp.get('embedding_dimensions', 768)}-dimensional "
        f"CodeBERT semantic embedding -- fused into a {fp.get('total_dimensions', 792)}-dimensional vector and classified "
        f"by a trained XGBoost model" + (f" ({eval_curves.get('xgboost', {}).get('roc_curve', {}).get('auc', '-')} ROC AUC on the held-out test set)." if eval_curves and eval_curves.get("xgboost") else "."),
        ss["EntBody"],
    ))

    # ── Detected vulnerabilities ─────────────────────────────────────────────
    el.append(Paragraph("Detected Vulnerabilities", ss["EntSubTitle"]))
    if line_risks:
        ldata = [["Line", "Severity", "CWE", "Finding"]]
        for lr in line_risks[:30]:
            ldata.append([str(lr["line"]), str(lr["severity"]), ", ".join(lr.get("cwe", [])) or "-", "; ".join(lr["reasons"])[:90]])
        ltbl = Table(ldata, colWidths=[35, 45, 65, 335], repeatRows=1)
        ltbl.setStyle(TableStyle([
            ("GRID", (0, 0), (-1, -1), 0.4, _ENT_HAIRLINE),
            ("BACKGROUND", (0, 0), (-1, 0), _ENT_INK), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTSIZE", (0, 0), (-1, -1), 8),
        ]))
        el.append(ltbl)
    else:
        el.append(Paragraph("No line-level findings were flagged by the heuristic scanner.", ss["EntBody"]))

    # ── AI explanation ───────────────────────────────────────────────────────
    el.append(Paragraph("AI Explanation", ss["EntSubTitle"]))
    if intel.get("dangerous_apis"):
        for d in intel["dangerous_apis"][:6]:
            el.append(Paragraph(f"&bull; <b>{d['api']}()</b> (line {d['line']}) -- {d.get('description') or 'flagged as a commonly-misused API.'}", ss["EntBody"]))
    else:
        el.append(Paragraph(
            "No single dangerous API call dominates the signal -- the verdict is driven primarily by CodeBERT's semantic "
            "embedding in combination with structural (AST/metric) features rather than one identifiable call.",
            ss["EntBody"],
        ))

    el.append(PageBreak())

    # ── Recommendations ───────────────────────────────────────────────────────
    el.append(Paragraph("Recommendations", ss["EntSectionTitle"]))
    if recs:
        for panel in recs:
            el.append(Paragraph(panel["title"], ss["EntSubTitle"]))
            for tip in panel.get("tips", []):
                el.append(Paragraph(f"&bull; {tip}", ss["EntBody"]))
    else:
        el.append(Paragraph("No specific recommendations for this file.", ss["EntBody"]))

    # ── Appendix: function statistics + source ──────────────────────────────
    el.append(Paragraph("Appendix A -- Function Statistics", ss["EntSubTitle"]))
    if intel.get("available") and intel.get("functions"):
        fdata = [["Function", "LOC", "CC", "Nesting", "Calls", "MI"]]
        for f in intel["functions"][:25]:
            fdata.append([f["name"], str(f["loc"]), str(f["cyclomatic_complexity"]), str(f["max_nesting"]), str(f["call_count"]), str(f["maintainability_index"])])
        ftbl = Table(fdata, colWidths=[150, 50, 40, 55, 45, 50], repeatRows=1)
        ftbl.setStyle(TableStyle([
            ("GRID", (0, 0), (-1, -1), 0.4, _ENT_HAIRLINE),
            ("BACKGROUND", (0, 0), (-1, 0), _ENT_INK), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTSIZE", (0, 0), (-1, -1), 8),
        ]))
        el.append(ftbl)

    el.append(Paragraph("Appendix B -- Source Code", ss["EntSubTitle"]))
    code_lines = (scan.get("code") or "").split("\n")
    for i in range(0, len(code_lines), 60):
        chunk = "\n".join(f"{i + j + 1:>4}  {l}" for j, l in enumerate(code_lines[i:i + 60]))
        el.append(Paragraph(chunk.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\n", "<br/>"), ss["EntCode"]))

    doc.build(el)
    return buf.getvalue()


def build_enterprise_project_pdf(project: dict) -> bytes:
    """
    Executive-grade PDF for a whole scanned repository/project (Phase 9 --
    Repository Scanner's flagship export). Same enterprise cover-page look
    as build_enterprise_pdf, rolled up to repository scope: repository
    score, folder scores, top vulnerable files, aggregated dangerous APIs
    and CWEs with mitigation guidance from the static knowledge base, and
    a full file appendix -- entirely derived from the already-aggregated
    /api/project/{batch_id}/summary payload. No new model, no retraining.
    """
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, topMargin=20 * mm, bottomMargin=20 * mm, leftMargin=20 * mm, rightMargin=20 * mm)
    ss = _enterprise_styles()
    el = []

    files = project["files"]
    total = project["total_files"]
    security_score = project["security_score"]
    grade = _grade(security_score)
    if security_score < 40:
        risk_color = colors.HexColor("#d03b3b")
    elif security_score < 70:
        risk_color = colors.HexColor("#c98500")
    else:
        risk_color = colors.HexColor("#0ca30c")

    # ── Cover page ──────────────────────────────────────────────────────────
    el.append(Spacer(1, 50))
    el.append(Table([[""]], colWidths=[170 * mm], rowHeights=[3], style=TableStyle([("BACKGROUND", (0, 0), (-1, -1), risk_color)])))
    el.append(Spacer(1, 26))
    el.append(Paragraph("SecureCode AI", ss["EntCoverSub"]))
    el.append(Paragraph("Repository Security Report", ss["EntCoverTitle"]))
    el.append(Spacer(1, 8))
    el.append(Paragraph(f"{project['project_name']} &middot; {total} files", ss["EntCoverSub"]))
    el.append(Paragraph(f"Generated {dt.datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')}", ss["EntMuted"]))
    el.append(Spacer(1, 40))
    highest = project.get("highest_risk_file")
    el.append(_ent_kv_table([
        ["Repository Score", f"{security_score:.0f} / 100  (Grade {grade})"],
        ["Total Files", str(total)],
        ["Safe Files", str(project["safe_files"])],
        ["Vulnerable Files", str(project["vulnerable_files"])],
        ["Functions Analyzed", str(project.get("function_count", "-"))],
        ["Highest Risk File", highest["filename"] if highest else "-"],
    ]))
    el.append(Spacer(1, 60))
    el.append(HRFlowable(width="100%", color=_ENT_HAIRLINE, thickness=0.6))
    el.append(Spacer(1, 8))
    el.append(Paragraph(
        "Automated repository-wide analysis generated by a multi-modal AI classifier (CodeBERT semantic embeddings "
        "+ AST structural features + software metrics, fused and classified by a trained XGBoost model), aggregated "
        "across every file scanned in this project. Intended to inform a human security review, not replace one. "
        "Confidential -- for internal distribution.",
        ss["EntMuted"],
    ))
    el.append(PageBreak())

    # ── Repository summary ───────────────────────────────────────────────────
    el.append(Paragraph("Repository Summary", ss["EntSectionTitle"]))
    risk_dist = project.get("risk_distribution") or {}
    if risk_dist:
        labels = list(risk_dist.keys())
        values = [risk_dist[k] for k in labels]
        d = Drawing(460, 30 + 20 * len(labels))
        chart = HorizontalBarChart()
        chart.x, chart.y = 110, 10
        chart.width, chart.height = 320, 16 * len(labels)
        chart.data = [values]
        chart.categoryAxis.categoryNames = labels
        chart.categoryAxis.labels.fontSize = 8
        chart.categoryAxis.labels.fillColor = _ENT_INK
        chart.valueAxis.valueMin = 0
        chart.valueAxis.labels.fontSize = 7
        chart.bars.strokeWidth = 0
        chart.barWidth = 10
        for i, lab in enumerate(labels):
            chart.bars[(0, i)].fillColor = RISK_COLOR_MAP.get(lab, _ENT_ACCENT)
        d.add(chart)
        el.append(d)
        el.append(Spacer(1, 10))

    # ── Folder summary ───────────────────────────────────────────────────────
    el.append(Paragraph("Folder Summary", ss["EntSubTitle"]))
    folder_rows = _folder_scores(files)
    if folder_rows:
        fdata = [["Folder", "Files", "Avg Risk", "Worst Finding"]]
        for r in folder_rows[:20]:
            fdata.append([r["folder"], str(r["file_count"]), f"{r['avg_risk']:.1f}%", r["worst_risk"]])
        ftbl = Table(fdata, colWidths=[220, 60, 80, 100], repeatRows=1)
        ftbl.setStyle(TableStyle([
            ("GRID", (0, 0), (-1, -1), 0.4, _ENT_HAIRLINE),
            ("BACKGROUND", (0, 0), (-1, 0), _ENT_INK), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTSIZE", (0, 0), (-1, -1), 8),
        ]))
        el.append(ftbl)
    else:
        el.append(Paragraph("This project has no nested folder structure -- every file was scanned at the project root.", ss["EntBody"]))

    # ── Top vulnerable files ─────────────────────────────────────────────────
    el.append(Paragraph("Top Vulnerable Files", ss["EntSubTitle"]))
    flagged = sorted(files, key=lambda f: -f["vuln_probability"])[:20]
    if flagged:
        vdata = [["File", "Risk Level", "Probability", "Confidence"]]
        for f in flagged:
            vdata.append([f["filename"], f["risk_level"], f"{f['vuln_probability']:.1f}%", f"{f['confidence']:.1f}%"])
        vtbl = Table(vdata, colWidths=[220, 100, 80, 80], repeatRows=1)
        vtbl.setStyle(TableStyle([
            ("GRID", (0, 0), (-1, -1), 0.4, _ENT_HAIRLINE),
            ("BACKGROUND", (0, 0), (-1, 0), _ENT_INK), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTSIZE", (0, 0), (-1, -1), 8),
        ]))
        el.append(vtbl)
    else:
        el.append(Paragraph("No files were flagged as vulnerable in this project.", ss["EntBody"]))

    el.append(PageBreak())

    # ── Aggregated findings + AI explanation ────────────────────────────────
    el.append(Paragraph("Aggregated Findings", ss["EntSectionTitle"]))
    apis = project.get("most_dangerous_apis") or []
    if apis:
        el.append(Paragraph("Most Dangerous APIs", ss["EntSubTitle"]))
        for a in apis[:8]:
            el.append(Paragraph(f"&bull; <b>{a['api']}()</b> -- found {a['count']}&times; across the project", ss["EntBody"]))

    cwes = project.get("most_common_cwe") or []
    if cwes:
        el.append(Paragraph("Most Common CWE Categories", ss["EntSubTitle"]))
        for c in cwes[:8]:
            plural = "s" if c["count"] != 1 else ""
            el.append(Paragraph(f"&bull; <b>{c['cwe']}</b> -- {c['name']} ({c['count']} occurrence{plural})", ss["EntBody"]))
    if not apis and not cwes:
        el.append(Paragraph(
            "No dangerous API calls or CWE-classified findings were detected across this project's files.",
            ss["EntBody"],
        ))

    # ── Recommendations (per top CWE, from the static knowledge base) ───────
    el.append(Paragraph("Recommendations", ss["EntSectionTitle"]))
    if cwes:
        for c in cwes[:5]:
            entry = knowledge_base.lookup(c["cwe"])
            el.append(Paragraph(f"{c['cwe']} -- {entry['name']}", ss["EntSubTitle"]))
            for tip in (entry.get("mitigation") or [])[:3]:
                el.append(Paragraph(f"&bull; {tip}", ss["EntBody"]))
    else:
        el.append(Paragraph("No CWE-classified findings across this project -- no specific remediation guidance to surface.", ss["EntBody"]))

    # ── Architecture ──────────────────────────────────────────────────────────
    el.append(Paragraph("Architecture Overview", ss["EntSubTitle"]))
    el.append(Paragraph(
        f"Each of the {total} files in this repository was analyzed independently through the same three-branch "
        "pipeline -- AST structural features, software-quality metrics, and a CodeBERT semantic embedding -- fused "
        "and classified by a trained XGBoost model. This report aggregates those independent, per-file verdicts "
        "into repository-, folder-, and file-level rollups; no model was retrained or fine-tuned to produce this "
        "summary.",
        ss["EntBody"],
    ))

    el.append(PageBreak())

    # ── Appendix: full file listing ──────────────────────────────────────────
    el.append(Paragraph("Appendix -- All Scanned Files", ss["EntSectionTitle"]))
    adata = [["File", "Risk Level", "Probability", "LOC"]]
    for f in files[:200]:
        adata.append([f["filename"], f["risk_level"], f"{f['vuln_probability']:.1f}%", str(f.get("loc", "-"))])
    atbl = Table(adata, colWidths=[240, 90, 80, 70], repeatRows=1)
    atbl.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.4, _ENT_HAIRLINE),
        ("BACKGROUND", (0, 0), (-1, 0), _ENT_INK), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTSIZE", (0, 0), (-1, -1), 8),
    ]))
    el.append(atbl)
    if len(files) > 200:
        el.append(Spacer(1, 6))
        el.append(Paragraph(f"...and {len(files) - 200} more files (truncated for report length).", ss["EntMuted"]))

    doc.build(el)
    return buf.getvalue()
