    _pptx_textbox(s2, 0.8, 2.5, 8, 0.5, f"Risk Level: {scan['risk_level']}", size=16, color=_PPTX_TEXT)
    _pptx_textbox(s2, 0.8, 3.0, 8, 0.5, f"Vulnerability Probability: {scan['vuln_probability']:.1f}%", size=16, color=_PPTX_TEXT)
    _pptx_textbox(s2, 0.8, 3.5, 8, 0.5, f"Confidence: {scan['confidence']:.1f}%", size=16, color=_PPTX_TEXT)
    _pptx_textbox(s2, 0.8, 4.0, 8, 0.5, f"Model: {scan['model_used']}", size=16, color=_PPTX_TEXT)

    # Slide 3: Findings
    s3 = _pptx_blank_slide(prs)
    _pptx_textbox(s3, 0.8, 0.5, 11.7, 0.8, "Line-Level Findings", size=28, bold=True, color=_PPTX_ACCENT)
    if line_risks:
        y = 1.6
        for lr in line_risks[:8]:
            cwe = ", ".join(lr.get("cwe", [])) or "-"
            _pptx_textbox(s3, 0.8, y, 11.7, 0.5, f"Line {lr['line']}  ({cwe})  —  {'; '.join(lr['reasons'])[:100]}", size=14, color=_PPTX_TEXT)
            y += 0.55
    else:
        _pptx_textbox(s3, 0.8, 1.8, 11.7, 0.6, "No specific line-level findings were flagged.", size=16, color=_PPTX_MUTED)

    # Slide 4: Recommendations
    s4 = _pptx_blank_slide(prs)
    _pptx_textbox(s4, 0.8, 0.5, 11.7, 0.8, "Recommendations", size=28, bold=True, color=_PPTX_ACCENT)
    if recs:
        y = 1.6
        for panel in recs[:4]:
            _pptx_textbox(s4, 0.8, y, 11.7, 0.4, panel["title"], size=18, bold=True, color=_PPTX_TEXT)
            y += 0.45
            for tip in panel.get("tips", [])[:2]:
                _pptx_textbox(s4, 1.2, y, 11.0, 0.4, f"• {tip}", size=13, color=_PPTX_MUTED)
                y += 0.4
            y += 0.15
    else:
        _pptx_textbox(s4, 0.8, 1.8, 11.7, 0.6, "No specific recommendations for this file.", size=16, color=_PPTX_MUTED)

    buf = io.BytesIO()
    prs.save(buf)
    return buf.getvalue()


