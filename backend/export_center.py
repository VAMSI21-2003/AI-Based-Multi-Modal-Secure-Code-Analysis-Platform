_PPTX_BG = PptxRGBColor(0x0D, 0x0D, 0x0D)
_PPTX_ACCENT = PptxRGBColor(0x39, 0x87, 0xE5)
_PPTX_TEXT = PptxRGBColor(0xFF, 0xFF, 0xFF)
_PPTX_MUTED = PptxRGBColor(0xC3, 0xC2, 0xB7)
_PPTX_CRITICAL = PptxRGBColor(0xD0, 0x3B, 0x3B)
_PPTX_GOOD = PptxRGBColor(0x0C, 0xA3, 0x0C)


def _pptx_blank_slide(prs):
    slide = prs.slides.add_slide(prs.slide_layouts[6])
    bg = slide.background
    bg.fill.solid()
    bg.fill.fore_color.rgb = _PPTX_BG
    return slide


def _pptx_textbox(slide, left, top, width, height, text, size=18, bold=False, color=_PPTX_TEXT, align=PP_ALIGN.LEFT):
    box = slide.shapes.add_textbox(PptxInches(left), PptxInches(top), PptxInches(width), PptxInches(height))
    tf = box.text_frame
    tf.word_wrap = True
    p = tf.paragraphs[0]
    p.alignment = align
    run = p.add_run()
    run.text = text
    run.font.size = PptxPt(size)
    run.font.bold = bold
    run.font.color.rgb = color
    return box


def build_pptx_report(scan: dict, line_risks: list, recs: list, intel: dict) -> bytes:
    prs = Presentation()
    prs.slide_width = PptxInches(13.333)
