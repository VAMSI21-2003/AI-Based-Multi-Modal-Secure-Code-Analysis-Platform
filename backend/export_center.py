def _styles():
    ss = getSampleStyleSheet()
    ss.add(ParagraphStyle("H1", parent=ss["Heading1"], textColor=INK, fontSize=22, spaceAfter=4))
    ss.add(ParagraphStyle("H2", parent=ss["Heading2"], textColor=ACCENT, fontSize=13, spaceBefore=14, spaceAfter=6))
    ss.add(ParagraphStyle("Body", parent=ss["Normal"], textColor=INK, fontSize=9.5, leading=13))
    ss.add(ParagraphStyle("Muted", parent=ss["Normal"], textColor=MUTED, fontSize=9))
    return ss


def build_executive_pdf(scan: dict) -> bytes:
    """One page, minimal jargon -- for a manager/stakeholder audience."""
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, topMargin=22 * mm, bottomMargin=20 * mm)
    ss = _styles()
    el = []

    safety_score = max(0.0, 100.0 - scan["vuln_probability"])
    grade = _grade(safety_score)
    verdict_word = "requires attention" if scan["verdict"] == "VULNERABLE" else "looks safe"

    el.append(Paragraph("Executive Summary", ss["H1"]))
    el.append(Paragraph(f"Project: <b>{scan.get('project_name', 'Untitled')}</b> &nbsp;|&nbsp; File: <b>{scan.get('filename', '-')}</b>", ss["Body"]))
    el.append(Paragraph(f"Generated {dt.datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')}", ss["Muted"]))
    el.append(Spacer(1, 16))

    el.append(Paragraph(
        f"This file <b>{verdict_word}</b>. The automated analysis assigns it a security grade of "
        f"<b>{grade}</b> (safety score {safety_score:.0f}/100). "
        f"{'Immediate review by a developer is recommended before this code is deployed.' if scan['verdict'] == 'VULNERABLE' else 'No further action is required at this time.'}",
        ss["Body"],
    ))
    el.append(Spacer(1, 14))

    data = [
        ["Risk Level", scan["risk_level"]],
        ["Confidence", f"{scan['confidence']:.0f}%"],
        ["Model Used", scan["model_used"]],
        ["Lines of Code", str(scan.get("loc", "-"))],
    ]
    tbl = Table(data, colWidths=[160, 300])
    tbl.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e1e0d9")),
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#f9f9f7")),
        ("TOPPADDING", (0, 0), (-1, -1), 6), ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    el.append(tbl)
    el.append(Spacer(1, 16))
    el.append(Paragraph(
        "This summary is generated by an automated multi-modal AI classifier (CodeBERT + AST + software metrics, "
        "XGBoost) and should inform, not replace, a human security review.",
        ss["Muted"],
    ))

    doc.build(el)
    return buf.getvalue()


def build_developer_pdf(scan: dict, line_risks: list, recs: list, intel: dict) -> bytes:
    """Full technical deep-dive -- for the engineer who has to fix it."""
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, topMargin=18 * mm, bottomMargin=18 * mm)
    ss = _styles()
    el = []

    el.append(Paragraph("Developer Report", ss["H1"]))
    el.append(Paragraph(f"{scan.get('filename', '-')} — {scan.get('project_name', '')}", ss["Body"]))
    el.append(Paragraph(f"Generated {dt.datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')}", ss["Muted"]))

    el.append(Paragraph("Verdict & Scores", ss["H2"]))
    scores = intel.get("scores", {}) if intel.get("available") else {}
    data = [
        ["Verdict", scan["verdict"]], ["Risk Level", scan["risk_level"]],
        ["Vulnerability Probability", f"{scan['vuln_probability']:.2f}%"],
        ["Quality Score", f"{scores.get('quality', '-')}"],
        ["Maintainability Index", f"{scores.get('maintainability_index', '-')}"],
        ["Security Score", f"{scores.get('security_score', '-')}"],
        ["Performance Score", f"{scores.get('performance_score', '-')}"],
    ]
    tbl = Table(data, colWidths=[200, 260])
    tbl.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e1e0d9")), ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#f9f9f7"))]))
    el.append(tbl)

    if intel.get("available") and intel.get("functions"):
        el.append(Paragraph("Function Statistics", ss["H2"]))
        fdata = [["Function", "LOC", "CC", "Nesting", "Calls", "MI"]]
        for f in intel["functions"][:25]:
            fdata.append([f["name"], str(f["loc"]), str(f["cyclomatic_complexity"]), str(f["max_nesting"]), str(f["call_count"]), str(f["maintainability_index"])])
        ftbl = Table(fdata, colWidths=[150, 50, 40, 55, 45, 50], repeatRows=1)
        ftbl.setStyle(TableStyle([
            ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#e1e0d9")),
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1a1a19")), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTSIZE", (0, 0), (-1, -1), 8),
        ]))
        el.append(ftbl)

    if line_risks:
        el.append(Paragraph("Line-Level Findings", ss["H2"]))
        ldata = [["Line", "Severity", "CWE", "Reason"]]
        for lr in line_risks[:40]:
            ldata.append([str(lr["line"]), str(lr["severity"]), ", ".join(lr["cwe"]) or "-", "; ".join(lr["reasons"])[:80]])
        ltbl = Table(ldata, colWidths=[35, 45, 70, 330], repeatRows=1)
        ltbl.setStyle(TableStyle([
            ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#e1e0d9")),
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1a1a19")), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTSIZE", (0, 0), (-1, -1), 8),
        ]))
        el.append(ltbl)

    if recs:
        el.append(Paragraph("Recommendations", ss["H2"]))
        for panel in recs:
            el.append(Paragraph(f"<b>{panel['title']}</b>", ss["Body"]))
            for tip in panel.get("tips", []):
                el.append(Paragraph(f"&bull; {tip}", ss["Body"]))
            el.append(Spacer(1, 4))

    doc.build(el)
    return buf.getvalue()


def build_research_pdf(architecture: dict, eval_curves: dict) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, topMargin=20 * mm, bottomMargin=18 * mm)
    ss = _styles()
    el = []

    el.append(Paragraph("Research Appendix", ss["H1"]))
    el.append(Paragraph("Model architecture, dataset, and evaluation methodology", ss["Body"]))
    el.append(Paragraph(f"Generated {dt.datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')}", ss["Muted"]))

    el.append(Paragraph("Feature Pipeline", ss["H2"]))
    fp = architecture.get("feature_pipeline", {})
    data = [
        ["AST Structural Features", str(fp.get("ast_dimensions"))],
        ["Software Metrics", str(fp.get("metrics_dimensions"))],
        ["CodeBERT Embedding", str(fp.get("embedding_dimensions"))],
        ["Total Fused Vector", str(fp.get("total_dimensions"))],
    ]
    tbl = Table(data, colWidths=[220, 260])
    tbl.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e1e0d9")), ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#f9f9f7"))]))
    el.append(tbl)

    training = architecture.get("training")
    if training:
        el.append(Paragraph("Dataset & Training", ss["H2"]))
        data = [
            ["Total Samples", f"{training.get('n_samples', '-'):,}" if isinstance(training.get("n_samples"), int) else "-"],
            ["Training / Test Split", f"{training.get('n_train', '-')} / {training.get('n_test', '-')}"],
            ["Random Seed", str(training.get("random_state", "-"))],
        ]
        tbl = Table(data, colWidths=[220, 260])
        tbl.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e1e0d9")), ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#f9f9f7"))]))
        el.append(tbl)

    for model_name in ("xgboost", "random_forest"):
        m = eval_curves.get(model_name) if eval_curves else None
        if not m:
            continue
        el.append(Paragraph(f"{model_name.replace('_', ' ').title()} Evaluation", ss["H2"]))
        cm = m["confusion_matrix"]
        data = [
            ["True Negative", str(cm["tn"])], ["False Positive", str(cm["fp"])],
            ["False Negative", str(cm["fn"])], ["True Positive", str(cm["tp"])],
            ["ROC AUC", str(m["roc_curve"]["auc"])],
        ]
        tbl = Table(data, colWidths=[220, 260])
        tbl.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e1e0d9")), ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#f9f9f7"))]))
        el.append(tbl)
        el.append(Spacer(1, 8))

    doc.build(el)
    return buf.getvalue()


